from ucimlrepo import fetch_ucirepo
import pandas as pd
import os
import matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
# =====================================================
# Create output folder
# =====================================================

OUTPUT_DIR = "processed_datasets"
os.makedirs(OUTPUT_DIR, exist_ok=True)

VISUALIZATION_DIR = os.path.join(
    OUTPUT_DIR,
    "appliance_energy_visualizations"
)

os.makedirs(VISUALIZATION_DIR, exist_ok=True)

print("\nSTARTING DATASET PREPARATION")
print("=" * 80)

# =====================================================
# DATASET 3 - Appliance Energy Prediction
# =====================================================

print("\nProcessing Appliance Energy Prediction...")

appliance = fetch_ucirepo(id=374)

X = appliance.data.features
y = appliance.data.targets

df = pd.concat([X, y], axis=1)

#to understand the number of records and features
print("\nDataset Shape:")
print(df.shape)

#to understand data type of each parameter and identify non-null values.
print("\nDataset Information:")
print(df.info())

# to understand the target and features 
print("\nVariables:")
print(appliance.variables)

df.to_csv(
    f"{OUTPUT_DIR}/appliance_energy_original.csv",
    index=False
)

print("Saved: appliance_energy_original.csv")

# =====================================================
# EXPLORATORY DATA ANALYSIS
# =====================================================

# =====================================================
# TARGET VARIABLE SUMMARY
# =====================================================
# Summarize the target variable.
print("\n" + "=" * 80)
print("TARGET VARIABLE SUMMARY")
print("=" * 80)

print("\nAppliance Energy Consumption (Appliances)")
print(y["Appliances"].describe())

# The mean is higher than the median, indicating a
# positively (right) skewed distribution.

# Approximately 75% of the observations have appliance
# energy consumption of 100 Wh or below, while the
# maximum value reaches 1080 Wh. This indicates the
# presence of relatively few high energy consumption values.

# Therefore, K-Means clustering is applied to identify
# natural energy consumption groups.

# =====================================================
# TARGET VISUALIZATION
# =====================================================

# Visualize the target variable to understand its
# distribution and assess whether it exhibits natural
# groupings suitable for K-Means clustering.

plt.figure(figsize=(6,4))

plt.hist(
    y["Appliances"],
    bins=20
)

plt.title("Appliance Energy Consumption")
plt.xlabel("Energy Consumption (Wh)")
plt.ylabel("Frequency")
plt.grid(True)

plt.savefig(
    os.path.join(
        VISUALIZATION_DIR,
        "01_appliance_energy_consumption_distribution.png"
    ),
    dpi=300,
    bbox_inches="tight"
)

plt.show()
plt.close()

# The target distribution indicates potential groupings.
# Therefore, K-Means clustering will be applied.

# =====================================================
# PREPARE TARGET VARIABLE FOR CLUSTERING
# =====================================================

# Standardize the target variable before applying
# K-Means clustering. Since K-Means is a distance-based
# algorithm, standardization ensures that the target
# variable is scaled( where mean = 0 and standard
# deviation = 1) appropriately.

print("\n" + "=" * 80)
print("STANDARDIZING TARGET VARIABLE")
print("=" * 80)

# Select the target variable.
target_data = df[["Appliances"]]

# Standardize the target variable.
scaler = StandardScaler()

target_scaled = scaler.fit_transform(target_data)

# =====================================================
# ELBOW METHOD
# =====================================================

# The Elbow Method is used to identify the optimal number
# of clusters by analysing the Within-Cluster Sum of Squares (WCSS).

print("\n" + "=" * 80)
print("ELBOW METHOD")
print("=" * 80)

wcss = []

k_values = range(2, 11)

for k in k_values:

    kmeans = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    kmeans.fit(target_scaled)

    wcss.append(kmeans.inertia_)

    print(f"k = {k}, WCSS = {kmeans.inertia_:.2f}")

plt.figure(figsize=(8,5))

plt.plot(
    k_values,
    wcss,
    marker="o"
)

plt.title("Elbow Method")
plt.xlabel("Number of Clusters (k)")
plt.ylabel("WCSS")
plt.savefig(
    os.path.join(
        VISUALIZATION_DIR,
        "02_elbow_method.png"
    ),
    dpi=300,
    bbox_inches="tight"
)

plt.show()
plt.close()

# The Elbow Method indicates that the reduction in WCSS
# begins to slow down after k = 5. Therefore, k = 5 is
# considered a candidate for the optimal number of clusters.

# =====================================================
# SILHOUETTE SCORE
# =====================================================

# The Silhouette Score evaluates the quality of the clusters
# generated by K-Means. It ranges from -1 to 1, where values
# closer to 1 indicate well-separated and compact clusters.

print("\n" + "=" * 80)
print("SILHOUETTE SCORE")
print("=" * 80)

silhouette_scores = []

for k in range(2, 11):

    kmeans = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    labels = kmeans.fit_predict(target_scaled)

    score = silhouette_score(
        target_scaled,
        labels
    )

    silhouette_scores.append(score)

    print(f"k = {k}, Silhouette Score = {score:.4f}")

plt.figure(figsize=(8, 5))

plt.plot(
    range(2, 11),
    silhouette_scores,
    marker="o"
)

plt.title("Silhouette Score for Different Numbers of Clusters")
plt.xlabel("Number of Clusters (k)")
plt.ylabel("Silhouette Score")
plt.grid(True)

plt.savefig(
    os.path.join(
        VISUALIZATION_DIR,
        "03_silhouette_score.png"
    ),
    dpi=300,
    bbox_inches="tight"
)

plt.show()
plt.close()
# The Silhouette Score ranges from -1 to 1, where values
# closer to 1 indicate well-separated and compact clusters.
# Although k = 2 achieved the highest Silhouette Score (0.8462),
# k = 5 was selected because it provides a better balance with
# the Elbow Method and produces more meaningful energy
# consumption categories for subsequent analysis.

# =====================================================
# K-MEANS CLUSTERING
# =====================================================

# Based on the Elbow Method and Silhouette Score,
# k = 5 was selected as the optimal number of clusters.

kmeans = KMeans(
    n_clusters=5,
    random_state=42,
    n_init=10
)

clusters = kmeans.fit_predict(target_scaled)

df["Cluster"] = clusters
print("\n" + "=" * 80)
print("CLUSTER DISTRIBUTION")
print("=" * 80)

print(df["Cluster"].value_counts().sort_index())

cluster_summary = df.groupby("Cluster")["Appliances"].agg(
    ["count", "min", "max", "mean"]
)

print("\nCluster Summary")
print(cluster_summary.round(2))
plt.figure(figsize=(8,5))

plt.scatter(
    df.index,
    df["Appliances"],
    c=df["Cluster"],
    cmap="viridis",
    s=10
)

plt.title("K-Means Clusters for Appliance Energy Consumption")
plt.xlabel("Observation")
plt.ylabel("Appliance Energy Consumption (Wh)")
plt.colorbar(label="Cluster")
plt.grid(True)

plt.savefig(
    os.path.join(
        VISUALIZATION_DIR,
        "04_kmeans_energy_clusters.png"
    ),
    dpi=300,
    bbox_inches="tight"
)

plt.show()
plt.close()
cluster_mapping = {
    0: "Very Low",
    2: "Low",
    3: "Medium",
    1: "High",
    4: "Very High"
}

df["Consumption_Class"] = df["Cluster"].map(cluster_mapping)

print("\n" + "=" * 80)
print("CONSUMPTION CLASS DISTRIBUTION")
print("=" * 80)

print(df["Consumption_Class"].value_counts())

summary = df.groupby("Consumption_Class")["Appliances"].mean()

print("\nAverage Appliance Energy Consumption for Each Consumption Class")
print(summary.round(2))

df.to_csv(
    f"{OUTPUT_DIR}/appliance_energy_clustered.csv",
    index=False
)

print("Saved: appliance_energy_clustered.csv")

